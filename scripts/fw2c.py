#!/usr/bin/env python3
"""Generate FirmwareData.cpp from fetched linux-firmware files.
Usage: python3 -I scripts/fw2c.py <fwdir> <out.cpp>
Files are treated as opaque data (only magic bytes are checked)."""
import os, sys, hashlib

WMFW = "CS35L56_Rev3.11.16.wmfw"
BINS = ["cs35l56-b0-dsp1-misc-10431c63-spkid%d-amp%d.bin" % (s, a) for s in (0, 1) for a in (1, 2)]
# Linux names -> stored blob (WHENCE "Link:" entries for the wmfw)
TABLE = [("cirrus/cs35l56-b0-dsp1-misc-10431c63-spkid0.wmfw", WMFW),
         ("cirrus/cs35l56-b0-dsp1-misc-10431c63-spkid1.wmfw", WMFW)] + [("cirrus/" + b, b) for b in BINS]

def main():
    fwdir, out = sys.argv[1], sys.argv[2]
    blobs = {}
    for name in [WMFW] + BINS:
        with open(os.path.join(fwdir, name), "rb") as f:
            data = f.read()
        magic = b"WMFW" if name.endswith(".wmfw") else b"WMDR"
        if data[:4] != magic:
            sys.exit("bad magic in " + name)
        blobs[name] = data
    lines = ["// GENERATED by scripts/fw2c.py - do not edit.",
             "// Cirrus Logic CS35L56 firmware from linux-firmware (redistributable, see LICENSE.cirrus).",
             '#include "../src/Firmware.h"', "#include <string.h>", ""]
    ids = {}
    for i, (name, data) in enumerate(blobs.items()):
        ids[name] = "fw%d" % i
        lines.append("// %s sha256 %s" % (name, hashlib.sha256(data).hexdigest()))
        lines.append("static const uint8_t fw%d[%d] = {" % (i, len(data)))
        for off in range(0, len(data), 24):
            lines.append("  " + ",".join("0x%02x" % b for b in data[off:off + 24]) + ",")
        lines.append("};")
    lines.append("static const CsFwFile kFiles[] = {")
    for lname, blob in TABLE:
        lines.append('  { "%s", %s, %d },' % (lname, ids[blob], len(blobs[blob])))
    lines.append("};")
    lines += ["const CsFwFile *csFindFirmware(const char *n) {",
              "  for (unsigned i = 0; i < sizeof(kFiles) / sizeof(kFiles[0]); i++)",
              "    if (!strcmp(kFiles[i].name, n)) return &kFiles[i];",
              "  return nullptr;", "}", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))

main()
